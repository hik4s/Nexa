package com.nexa.finance.ui.theme

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * Centralized NEXA spacing scale.
 *
 * The spacing system follows a compact 4 dp base grid. Components should
 * consume these tokens instead of introducing arbitrary spacing values.
 */
object NexaSpacing {
    val xxs: Dp = 4.dp
    val xs: Dp = 8.dp
    val sm: Dp = 12.dp
    val md: Dp = 16.dp
    val lg: Dp = 20.dp
    val xl: Dp = 24.dp
    val xxl: Dp = 32.dp
    val xxxl: Dp = 40.dp
    val huge: Dp = 48.dp
    val hero: Dp = 64.dp
}
